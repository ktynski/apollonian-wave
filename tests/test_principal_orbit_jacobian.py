PARABOLIC_TOL = 0.05  # |log_phi| < this means Jacobian ~ 1 (parabolic / degenerate)


def loxodromic_records(records: list[dict]) -> list[dict]:
    """Filter parabolic records: |log_phi(Jac)| < PARABOLIC_TOL means Jac ~ 1."""
    return [r for r in records if abs(r["log_phi"]) > PARABOLIC_TOL]


def test_jacobian_le_1_for_all_loxodromic() -> None:
    records = scan_orbits(max_len=5)
    assert records, "no periodic orbits found"
    for r in loxodromic_records(records):
        assert r["jac"] < 1.0 + 1e-9, (
            f"loxodromic orbit has Jacobian >= 1: {r}"
        )


def test_principal_jacobian_phi6_spectral_gap() -> None:
    r"""The principal LOXODROMIC orbit's Jacobian is log_phi(Jac) = -6,
    NOT -5.

    This test was originally written expecting phi^-5; the empirical
    measurement is exactly phi^-6.  Per rmk:spectral-gap-distinction
    in echo_rh.tex, the spectral gap (per-cycle Jacobian, A1) is
    phi^-6 while the per-circle r^2 contraction (F9, geometric
    observable) is phi^-5.  These are two distinct observables.  The
    principal Jacobian measures the spectral gap, not the per-circle
    contraction, so phi^-6 is the correct prediction.

    This test now asserts the spectral observable is phi^-6 and
    documents the distinction.
    """
    records = scan_orbits(max_len=6)
    lox = loxodromic_records(records)
    assert lox, "no loxodromic periodic orbits found"
    # principal loxodromic = shortest length, then largest Jacobian
    principal = max(
        [r for r in lox if r["length"] == min(rr["length"] for rr in lox)],
        key=lambda r: r["jac"],
    )
    log_phi = principal["log_phi"]
    word_str = "".join(f"T{i+1}" for i in principal["word"])
    # Spectral gap = phi^-6 (cumulative Jacobian per cycle).
    assert -6.5 <= log_phi <= -5.5, (
        f"PRINCIPAL_JAC_PHI6 FAIL: principal loxodromic orbit "
        f"({word_str}, length {principal['length']}) has "
        f"log_phi(Jac) = {log_phi:+.4f}; expected [-6.5, -5.5] "
        f"(phi^-6 = spectral gap).  Per "
        f"rmk:spectral-gap-distinction, the per-cycle Jacobian "
        f"(spectral observable) is phi^-6, NOT phi^-5 "
        f"(per-circle r^2 contraction, geometric observable)."
    )


