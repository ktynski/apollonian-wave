def _print_orbit_table(records: list[dict]) -> None:
    print("\n  Periodic orbits up to length 6 (cyclically reduced primitive words):")
    print("  " + "-" * 76)
    print(f"  {'word':<22} {'len':>3}  {'|T'+chr(39)+'| product':>16}  {'log_phi':>10}")
    print("  " + "-" * 76)
    for r in records[:25]:
        word_str = "".join(f"T{i+1}" for i in r["word"])
        if len(word_str) > 20:
            word_str = word_str[:17] + "..."
        print(f"  {word_str:<22} {r['length']:>3}  {r['jac']:>16.6e}  "
              f"{r['log_phi']:>+10.3f}")
    print("  " + "-" * 76)


